import AppKit
import CryptoKit
import UniformTypeIdentifiers

/// Something in the tray. Files stay where they are, and the tray follows them if they're moved or
/// renamed; anything else (text, a link, a picture) is kept in the tray's own folder, as the app it
/// came from gave it, so copying it again gives back exactly what was copied.
struct TrayItem: Codable, Identifiable, Equatable {
    enum Kind: String, Codable {
        case files, image, link, text
    }

    let id: UUID
    var added: Date
    let kind: Kind
    /// Dropped on the notch: kept until it's removed. Copied: kept as long as chosen in Settings.
    var kept: Bool
    /// Files: where each one is.
    var bookmarks: [Data] = []
    /// Files' names, as they were last seen.
    var names: [String] = []
    /// Text and links: the start of the text, enough to show.
    var text: String?
    /// The app it was copied from, by bundle identifier.
    var app: String?
    /// What the app gave, one file each in the item's folder: the type, and the file's name.
    var types: [String] = []
    var files: [String] = []
    /// Two items with the same fingerprint hold the same thing: copying it again brings the one
    /// already there to the front rather than adding it twice.
    var fingerprint: String

    /// Copies, as copies go, are kept for 30 minutes, 8 hours or 7 days, as Spotlight's are.
    func expired(at date: Date, keep: ClipboardKeep) -> Bool {
        !kept && date.timeIntervalSince(added) > keep.seconds
    }

    /// The name under the item: a file's, or what kind of thing it is.
    var title: String {
        switch kind {
        case .files: names.count > 1 ? "\(names.count) Items" : names.first ?? "File"
        case .image: "Image"
        case .link: text.flatMap { URL(string: $0)?.host() }.map { $0.hasPrefix("www.") ? String($0.dropFirst(4)) : $0 } ?? "Link"
        case .text: "Text"
        }
    }
}

/// How long copies stay in the tray: Spotlight's own choices for its clipboard history.
enum ClipboardKeep: String, CaseIterable, Identifiable {
    case halfHour, eightHours, week

    var id: Self { self }
    var title: String {
        switch self {
        case .halfHour: "30 Minutes"
        case .eightHours: "8 Hours"
        case .week: "7 Days"
        }
    }

    var seconds: TimeInterval {
        switch self {
        case .halfHour: 30 * 60
        case .eightHours: 8 * 60 * 60
        case .week: 7 * 24 * 60 * 60
        }
    }

    static var current: ClipboardKeep {
        ClipboardKeep(rawValue: UserDefaults.standard.string(forKey: Preferences.trayClipboardKeep) ?? "") ?? .eightHours
    }
}

/// What's on a pasteboard, made into a tray item: the item, and what to keep in its folder.
struct TrayCapture {
    var item: TrayItem
    /// For each of the item's files, what goes in it.
    var data: [Data]

    /// Marks apps put on what's copied when it shouldn't be kept: passwords, things only passing
    /// through, things made on the fly (nspasteboard.org).
    static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "Pasteboard generator type",
        "com.typeit4me.clipping", "net.antelle.keeweb",
    ]

    /// Password managers, never kept from even if they forget the marks above.
    static let privateApps: Set<String> = [
        "com.apple.Passwords", "com.apple.keychainaccess", "com.1password.1password", "com.agilebits.onepassword7",
        "com.bitwarden.desktop", "com.lastpass.LastPass", "com.dashlane.dashlanephonefinal", "org.keepassxc.keepassxc",
    ]

    /// What's kept of text, in order: plain, then the richer versions apps paste when they can.
    private static let textTypes: [NSPasteboard.PasteboardType] = [.string, .rtf, .html, .rtfd]
    /// A picture: the first of these there is.
    private static let imageTypes: [NSPasteboard.PasteboardType] = [.png, .tiff, NSPasteboard.PasteboardType(UTType.jpeg.identifier)]
    /// Larger than this, a version isn't kept: a copy is never worth filling the disk.
    static let largest = 30 * 1024 * 1024
    /// The most of a text kept to show it.
    static let shownText = 2000

    /// Whatever's on the pasteboard, if it's worth keeping and allowed to be kept: files, a picture,
    /// a link, or text. Dropped, it's kept until removed; copied, for as long as chosen.
    static func make(from pasteboard: NSPasteboard, kept: Bool, app: String? = nil, now: Date = .now) -> TrayCapture? {
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: privateTypes), !(app.map(privateApps.contains) ?? false) else { return nil }
        let id = UUID()

        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let bookmarks = urls.compactMap { try? $0.bookmarkData() }
            guard bookmarks.count == urls.count else { return nil }
            return TrayCapture(
                item: TrayItem(
                    id: id, added: now, kind: .files, kept: kept, bookmarks: bookmarks, names: urls.map(\.lastPathComponent), app: app,
                    fingerprint: "files:" + urls.map(\.path).joined(separator: "\n")),
                data: [])
        }

        let string = pasteboard.string(forType: .string)
        let text = string?.trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
        // A picture copied on its own; a picture with words, as from a page, is kept as its words.
        if text.isEmpty, let type = pasteboard.availableType(from: imageTypes), let data = pasteboard.data(forType: type),
            data.count <= largest
        {
            let ext = UTType(type.rawValue)?.preferredFilenameExtension ?? "png"
            return TrayCapture(
                item: TrayItem(
                    id: id, added: now, kind: .image, kept: kept, app: app, types: [type.rawValue],
                    files: ["\(imageName(at: now)).\(ext)"], fingerprint: "image:" + digest(data)),
                data: [data])
        }

        guard !text.isEmpty, let string else { return nil }
        var kinds: [String] = [], files: [String] = [], data: [Data] = []
        for type in textTypes where types.contains(type.rawValue) {
            guard let value = pasteboard.data(forType: type), value.count <= largest else { continue }
            kinds.append(type.rawValue)
            files.append("\(kinds.count - 1).\(UTType(type.rawValue)?.preferredFilenameExtension ?? "data")")
            data.append(value)
        }
        let link = isLink(text)
        // A link copied from a browser also carries its address as a URL.
        if link, let url = pasteboard.data(forType: .URL), !kinds.contains(NSPasteboard.PasteboardType.URL.rawValue) {
            kinds.append(NSPasteboard.PasteboardType.URL.rawValue)
            files.append("\(kinds.count - 1).url")
            data.append(url)
        }
        return TrayCapture(
            item: TrayItem(
                id: id, added: now, kind: link ? .link : .text, kept: kept, text: String(string.prefix(shownText)), app: app,
                types: kinds, files: files, fingerprint: (link ? "link:" : "text:") + digest(Data(string.utf8))),
            data: data)
    }

    /// One web address and nothing else.
    static func isLink(_ text: String) -> Bool {
        guard !text.contains(where: \.isWhitespace), let url = URL(string: text), let scheme = url.scheme?.lowercased() else { return false }
        return ["http", "https"].contains(scheme) && url.host() != nil
    }

    /// As a screenshot is named, so a picture dragged out of the tray lands with a name that says
    /// when it was copied.
    static func imageName(at date: Date) -> String {
        let formatter = DateFormatter()
        formatter.locale = Locale(identifier: "en_US_POSIX")
        formatter.dateFormat = "yyyy-MM-dd 'at' HH.mm.ss"
        return "Image " + formatter.string(from: date)
    }

    private static func digest(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }
}
